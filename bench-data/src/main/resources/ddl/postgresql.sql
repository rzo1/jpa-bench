-- Target database: PostgreSQL 18.
-- Schema of the jpa-bench data model. This script is the ONLY source of the schema:
-- no provider may generate, update or validate it.
DROP TABLE IF EXISTS PRODUCT_TAG CASCADE;
DROP TABLE IF EXISTS PRODUCT_CATEGORY CASCADE;
DROP TABLE IF EXISTS ORDER_LINE CASCADE;
DROP TABLE IF EXISTS ORDERS CASCADE;
DROP TABLE IF EXISTS PRODUCT CASCADE;
DROP TABLE IF EXISTS CATEGORY CASCADE;
DROP TABLE IF EXISTS CUSTOMER CASCADE;
DROP TABLE IF EXISTS ST_PERSON CASCADE;
DROP TABLE IF EXISTS JN_EMPLOYEE CASCADE;
DROP TABLE IF EXISTS JN_CONTRACTOR CASCADE;
DROP TABLE IF EXISTS JN_PERSON CASCADE;

CREATE TABLE CATEGORY (
    ID          BIGINT        NOT NULL,
    NAME        VARCHAR(80)   NOT NULL,
    CONSTRAINT PK_CATEGORY PRIMARY KEY (ID)
);

CREATE TABLE PRODUCT (
    ID          BIGINT        NOT NULL,
    SKU         VARCHAR(32)   NOT NULL,
    NAME        VARCHAR(120)  NOT NULL,
    PRICE       NUMERIC(12,2) NOT NULL,
    CONSTRAINT PK_PRODUCT PRIMARY KEY (ID),
    CONSTRAINT UK_PRODUCT_SKU UNIQUE (SKU)
);

CREATE TABLE PRODUCT_CATEGORY (
    PRODUCT_ID  BIGINT        NOT NULL,
    CATEGORY_ID BIGINT        NOT NULL,
    CONSTRAINT PK_PRODUCT_CATEGORY PRIMARY KEY (PRODUCT_ID, CATEGORY_ID),
    CONSTRAINT FK_PC_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID),
    CONSTRAINT FK_PC_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY (ID)
);
CREATE INDEX IX_PC_CATEGORY ON PRODUCT_CATEGORY (CATEGORY_ID);

CREATE TABLE PRODUCT_TAG (
    PRODUCT_ID  BIGINT        NOT NULL,
    TAG         VARCHAR(40)   NOT NULL,
    CONSTRAINT PK_PRODUCT_TAG PRIMARY KEY (PRODUCT_ID, TAG),
    CONSTRAINT FK_PT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID)
);

CREATE TABLE CUSTOMER (
    ID          BIGINT        NOT NULL,
    FIRST_NAME  VARCHAR(60)   NOT NULL,
    LAST_NAME   VARCHAR(60)   NOT NULL,
    EMAIL       VARCHAR(120)  NOT NULL,
    CREATED_AT  DATE          NOT NULL,
    STREET      VARCHAR(120),
    CITY        VARCHAR(80),
    ZIP         VARCHAR(16),
    COUNTRY     VARCHAR(2),
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (ID),
    CONSTRAINT UK_CUSTOMER_EMAIL UNIQUE (EMAIL)
);
CREATE INDEX IX_CUSTOMER_CITY ON CUSTOMER (CITY);
CREATE INDEX IX_CUSTOMER_LAST_NAME ON CUSTOMER (LAST_NAME);

CREATE TABLE ORDERS (
    ID          BIGINT        NOT NULL,
    VERSION     INTEGER       NOT NULL,
    CUSTOMER_ID BIGINT        NOT NULL,
    ORDER_DATE  DATE          NOT NULL,
    STATUS      VARCHAR(16)   NOT NULL,
    TOTAL       NUMERIC(12,2) NOT NULL,
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID),
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (ID)
);
CREATE INDEX IX_ORDERS_CUSTOMER ON ORDERS (CUSTOMER_ID);
CREATE INDEX IX_ORDERS_STATUS_DATE ON ORDERS (STATUS, ORDER_DATE);
CREATE INDEX IX_ORDERS_DATE ON ORDERS (ORDER_DATE);

CREATE TABLE ORDER_LINE (
    ID          BIGINT        NOT NULL,
    ORDER_ID    BIGINT        NOT NULL,
    PRODUCT_ID  BIGINT        NOT NULL,
    LINE_NO     INTEGER       NOT NULL,
    QUANTITY    INTEGER       NOT NULL,
    UNIT_PRICE  NUMERIC(12,2) NOT NULL,
    CONSTRAINT PK_ORDER_LINE PRIMARY KEY (ID),
    CONSTRAINT FK_OL_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID),
    CONSTRAINT FK_OL_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID)
);
CREATE INDEX IX_OL_ORDER ON ORDER_LINE (ORDER_ID);
CREATE INDEX IX_OL_PRODUCT ON ORDER_LINE (PRODUCT_ID);

CREATE TABLE ST_PERSON (
    ID          BIGINT        NOT NULL,
    PTYPE       VARCHAR(8)    NOT NULL,
    NAME        VARCHAR(120)  NOT NULL,
    EMAIL       VARCHAR(120)  NOT NULL,
    DEPARTMENT  VARCHAR(40),
    SALARY      NUMERIC(12,2),
    AGENCY      VARCHAR(60),
    HOURLY_RATE NUMERIC(12,2),
    CONSTRAINT PK_ST_PERSON PRIMARY KEY (ID)
);
CREATE INDEX IX_ST_PERSON_PTYPE ON ST_PERSON (PTYPE);
CREATE INDEX IX_ST_PERSON_DEPARTMENT ON ST_PERSON (DEPARTMENT);

CREATE TABLE JN_PERSON (
    ID          BIGINT        NOT NULL,
    PTYPE       VARCHAR(8)    NOT NULL,
    NAME        VARCHAR(120)  NOT NULL,
    EMAIL       VARCHAR(120)  NOT NULL,
    CONSTRAINT PK_JN_PERSON PRIMARY KEY (ID)
);
CREATE INDEX IX_JN_PERSON_PTYPE ON JN_PERSON (PTYPE);

CREATE TABLE JN_EMPLOYEE (
    ID          BIGINT        NOT NULL,
    DEPARTMENT  VARCHAR(40),
    SALARY      NUMERIC(12,2),
    CONSTRAINT PK_JN_EMPLOYEE PRIMARY KEY (ID),
    CONSTRAINT FK_JN_EMPLOYEE_PERSON FOREIGN KEY (ID) REFERENCES JN_PERSON (ID)
);
CREATE INDEX IX_JN_EMPLOYEE_DEPARTMENT ON JN_EMPLOYEE (DEPARTMENT);

CREATE TABLE JN_CONTRACTOR (
    ID          BIGINT        NOT NULL,
    AGENCY      VARCHAR(60),
    HOURLY_RATE NUMERIC(12,2),
    CONSTRAINT PK_JN_CONTRACTOR PRIMARY KEY (ID),
    CONSTRAINT FK_JN_CONTRACTOR_PERSON FOREIGN KEY (ID) REFERENCES JN_PERSON (ID)
);
